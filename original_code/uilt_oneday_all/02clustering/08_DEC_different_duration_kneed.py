@dataclass
class FeatureBlock:
    """Container for features and their metadata."""

    features: np.ndarray
    wave_file: np.ndarray
    event: np.ndarray
    time: np.ndarray
    source: str


def natural_event_id(event_name: str) -> int:
    """Extract integer id from event name, e.g. event12 -> 12."""
    match = re.search(r"event(\d+)", str(event_name), flags=re.IGNORECASE)
    return int(match.group(1)) if match else 10**9


def parse_time_from_wave_file(wave_file: object) -> datetime | None:
    """
    Parse timestamps like event1_20170528T165000_Z.sac from wave file names.
    """
    text = str(wave_file)
    match = re.search(r"(\d{8}T\d{6})", text)
    if match is None:
        return None
    return datetime.strptime(match.group(1), "%Y%m%dT%H%M%S")


def event_from_filename(path: Path) -> str:
    """Extract event name from an npz file name."""
    match = re.search(r"(event\d+)", path.name, flags=re.IGNORECASE)
    if match is None:
        raise ValueError(f"Cannot parse event name from file: {path}")
    return match.group(1).lower()


def load_feature_block(npz_path: Path, fallback_event: str | None = None) -> FeatureBlock:
    """Load feature vectors and build event/time metadata."""
    if not npz_path.exists():
        raise FileNotFoundError(f"Feature file does not exist: {npz_path}")

    data = np.load(npz_path, allow_pickle=True)
    if "features" not in data:
        raise KeyError(f"'features' not found in {npz_path}")
    if "wave_file" not in data:
        raise KeyError(f"'wave_file' not found in {npz_path}")

    features = np.asarray(data["features"], dtype=np.float32)
    wave_file = np.asarray(data["wave_file"])

    if "event" in data:
        event = np.asarray(data["event"]).astype(str)
    else:
        if fallback_event is None:
            fallback_event = event_from_filename(npz_path)
        event = np.full(len(features), fallback_event, dtype=object)

    if len(features) != len(wave_file):
        raise ValueError(
            f"features and wave_file length mismatch in {npz_path}: "
            f"{len(features)} vs {len(wave_file)}"
        )
    if len(features) != len(event):
        raise ValueError(
            f"features and event length mismatch in {npz_path}: "
            f"{len(features)} vs {len(event)}"
        )

    parsed_times = np.array(
        [parse_time_from_wave_file(item) for item in wave_file],
        dtype=object,
    )
    if any(item is None for item in parsed_times):
        raise ValueError(f"Failed to parse some timestamps from {npz_path}")

    features = np.nan_to_num(features, nan=0.0, posinf=0.0, neginf=0.0)

    return FeatureBlock(
        features=features,
        wave_file=wave_file,
        event=event,
        time=parsed_times,
        source=str(npz_path),
    )


def select_last_duration(block: FeatureBlock, duration_hours: float) -> FeatureBlock:
    """
    Select the last duration_hours before the final timestamp of each event.

    For per-event files this is simply the last duration_hours of the file.
    For global files, the operation is applied event by event and then merged.
    """
    selected_indices: list[np.ndarray] = []

    for event_name in sorted(set(block.event), key=natural_event_id):
        event_mask = block.event == event_name
        event_indices = np.where(event_mask)[0]
        event_times = block.time[event_indices]
        end_time = max(event_times)
        start_time = end_time - timedelta(hours=float(duration_hours))

        keep = np.array(
            [
                (item > start_time) and (item <= end_time)
                for item in event_times
            ],
            dtype=bool,
        )
        selected_indices.append(event_indices[keep])

    if not selected_indices:
        raise ValueError("No samples were selected.")

    indices = np.concatenate(selected_indices)
    indices = np.sort(indices)

    return FeatureBlock(
        features=block.features[indices],
        wave_file=block.wave_file[indices],
        event=block.event[indices],
        time=block.time[indices],
        source=block.source,
    )


def prepare_features(features: np.ndarray) -> np.ndarray:
    """Standardize features for KMeans if configured."""
    x = np.asarray(features, dtype=np.float32)
    x = np.nan_to_num(x, nan=0.0, posinf=0.0, neginf=0.0)

    if STANDARDIZE_FEATURES:
        scaler = StandardScaler()
        x = scaler.fit_transform(x)

    return x


def detect_elbow_by_max_distance(k_values: Iterable[int], wcss_values: Iterable[float]) -> int:
    """
    Detect an elbow by the maximum perpendicular distance to the straight line
    connecting the first and last WCSS points.

    This is a stable local fallback when the kneed package is unavailable.
    """
    k_values = np.asarray(list(k_values), dtype=float)
    wcss_values = np.asarray(list(wcss_values), dtype=float)

    if len(k_values) < 3:
        return int(k_values[0]) if len(k_values) else DEFAULT_K

    if np.allclose(wcss_values.max(), wcss_values.min()):
        return DEFAULT_K

    x = (k_values - k_values.min()) / (k_values.max() - k_values.min())
    y = (wcss_values - wcss_values.min()) / (wcss_values.max() - wcss_values.min())

    p1 = np.array([x[0], y[0]])
    p2 = np.array([x[-1], y[-1]])
    line_norm = np.linalg.norm(p2 - p1)

    if line_norm == 0:
        return DEFAULT_K

    distances = []
    for xi, yi in zip(x, y):
        p = np.array([xi, yi])
        distance = abs(np.cross(p2 - p1, p1 - p)) / line_norm
        distances.append(distance)

    return int(k_values[int(np.argmax(distances))])


def detect_elbow(k_values: Iterable[int], wcss_values: Iterable[float]) -> tuple[int, str]:
    """
    Prefer kneed.KneeLocator when installed; otherwise use max-distance elbow.
    """
    k_values = list(k_values)
    wcss_values = list(wcss_values)

    try:
        from kneed import KneeLocator

        knee = KneeLocator(
            k_values,
            wcss_values,
            curve="convex",
            direction="decreasing",
        )
        if knee.knee is not None:
            return int(knee.knee), "kneed.KneeLocator"
    except Exception as exc:
        warnings.warn(f"KneeLocator unavailable or failed: {exc}")

    return detect_elbow_by_max_distance(k_values, wcss_values), "max_distance_elbow"


def compute_scores(x: np.ndarray, labels: np.ndarray) -> dict[str, float]:
    """Compute internal cluster validity scores safely."""
    scores = {
        "silhouette": np.nan,
        "calinski_harabasz": np.nan,
        "davies_bouldin": np.nan,
    }

    unique_labels = np.unique(labels)
    if len(unique_labels) < 2 or len(unique_labels) >= len(labels):
        return scores

    x_eval = x
    labels_eval = labels
    if len(x) > MAX_SILHOUETTE_SAMPLES:
        rng = np.random.default_rng(RANDOM_STATE)
        idx = rng.choice(len(x), size=MAX_SILHOUETTE_SAMPLES, replace=False)
        x_eval = x[idx]
        labels_eval = labels[idx]

    try:
        scores["silhouette"] = float(silhouette_score(x_eval, labels_eval))
    except Exception as exc:
        warnings.warn(f"silhouette_score failed: {exc}")

    try:
        scores["calinski_harabasz"] = float(calinski_harabasz_score(x_eval, labels_eval))
    except Exception as exc:
        warnings.warn(f"calinski_harabasz_score failed: {exc}")

    try:
        scores["davies_bouldin"] = float(davies_bouldin_score(x_eval, labels_eval))
    except Exception as exc:
        warnings.warn(f"davies_bouldin_score failed: {exc}")

    return scores


def fit_kmeans(x: np.ndarray, k: int, use_minibatch: bool):
    """Fit KMeans or MiniBatchKMeans."""
    if use_minibatch:
        model = MiniBatchKMeans(
            n_clusters=k,
            batch_size=GLOBAL_BATCH_SIZE,
            n_init=N_INIT,
            random_state=RANDOM_STATE,
        )
    else:
        model = KMeans(
            n_clusters=k,
            n_init=N_INIT,
            random_state=RANDOM_STATE,
        )

    labels = model.fit_predict(x)
    return model, labels


def analyse_one_block(
    block: FeatureBlock,
    duration_hours: float,
    analysis_scope: str,
    use_minibatch: bool = False,
) -> tuple[pd.DataFrame, dict[str, object]]:
    """Run KMeans over K_MIN..K_MAX for one feature block."""
    window_block = select_last_duration(block, duration_hours)
    sample_count = len(window_block.features)

    if sample_count < K_MIN + 1:
        raise ValueError(
            f"Too few samples for {analysis_scope}, duration={duration_hours}: "
            f"{sample_count}"
        )

    k_max = min(K_MAX, sample_count - 1)
    x = prepare_features(window_block.features)

    records = []
    for k in range(K_MIN, k_max + 1):
        model, labels = fit_kmeans(x, k, use_minibatch=use_minibatch)
        scores = compute_scores(x, labels)
        cluster_sizes = np.bincount(labels, minlength=k)

        records.append(
            {
                "analysis_scope": analysis_scope,
                "duration_hours": duration_hours,
                "K": k,
                "sample_count": sample_count,
                "event_count": len(set(window_block.event)),
                "WCSS": float(model.inertia_),
                "silhouette": scores["silhouette"],
                "calinski_harabasz": scores["calinski_harabasz"],
                "davies_bouldin": scores["davies_bouldin"],
                "min_cluster_size": int(cluster_sizes.min()),
                "max_cluster_size": int(cluster_sizes.max()),
                "cluster_sizes": ",".join(map(str, cluster_sizes.tolist())),
                "source": block.source,
            }
        )

    metric_df = pd.DataFrame(records)

    best_k_wcss, elbow_method = detect_elbow(metric_df["K"], metric_df["WCSS"])
    best_k_silhouette = int(metric_df.loc[metric_df["silhouette"].idxmax(), "K"])
    best_k_ch = int(metric_df.loc[metric_df["calinski_harabasz"].idxmax(), "K"])
    best_k_db = int(metric_df.loc[metric_df["davies_bouldin"].idxmin(), "K"])

    summary = {
        "analysis_scope": analysis_scope,
        "duration_hours": duration_hours,
        "recommended_k": int(best_k_wcss),
        "k_selection_method": elbow_method,
        "best_k_wcss_elbow": int(best_k_wcss),
        "best_k_silhouette": best_k_silhouette,
        "best_k_calinski_harabasz": best_k_ch,
        "best_k_davies_bouldin": best_k_db,
        "sample_count": sample_count,
        "event_count": len(set(window_block.event)),
        "window_start": min(window_block.time),
        "window_end": max(window_block.time),
        "source": block.source,
    }

    return metric_df, summary


def plot_metric_curves(metric_df: pd.DataFrame, summary: dict[str, object], save_path: Path) -> None:
    """Plot WCSS and three internal scores for one analysis block."""
    fig, axes = plt.subplots(2, 2, figsize=(11, 8))
    axes = axes.ravel()

    recommended_k = int(summary["recommended_k"])
    duration_hours = summary["duration_hours"]
    title_prefix = summary["analysis_scope"]

    plot_specs = [
        ("WCSS", "WCSS / inertia", False),
        ("silhouette", "Silhouette score", True),
        ("calinski_harabasz", "Calinski-Harabasz score", True),
        ("davies_bouldin", "Davies-Bouldin index", False),
    ]

    for ax, (column, ylabel, _) in zip(axes, plot_specs):
        ax.plot(metric_df["K"], metric_df[column], marker="o", linewidth=1.8)
        ax.axvline(
            recommended_k,
            color="red",
            linestyle="--",
            linewidth=1.2,
            label=f"recommended K={recommended_k}",
        )
        ax.set_xlabel("Number of clusters K")
        ax.set_ylabel(ylabel)
        ax.grid(alpha=0.3)
        ax.legend(fontsize=9)

    fig.suptitle(f"{title_prefix}, last {duration_hours:g} h")
    fig.tight_layout()
    save_path.parent.mkdir(parents=True, exist_ok=True)
    fig.savefig(save_path, dpi=300)
    plt.close(fig)


def write_excel_outputs(
    per_event_summary: pd.DataFrame,
    global_summary: pd.DataFrame,
    all_metrics: pd.DataFrame,
) -> Path:
    """Save all result tables to one workbook and several CSV files."""
    OUTPUT_DIR.mkdir(parents=True, exist_ok=True)
    TABLE_DIR.mkdir(parents=True, exist_ok=True)

    summary_path = OUTPUT_DIR / "different_duration_best_k_summary.xlsx"

    readme = pd.DataFrame(
        [
            {
                "item": "recommended_k",
                "description": (
                    "Main K used by later DEC analysis. It is selected by the "
                    "WCSS elbow/Kneedle criterion."
                ),
            },
            {
                "item": "best_k_silhouette",
                "description": "Reference K where Silhouette score reaches its maximum.",
            },
            {
                "item": "best_k_calinski_harabasz",
                "description": "Reference K where Calinski-Harabasz score reaches its maximum.",
            },
            {
                "item": "best_k_davies_bouldin",
                "description": "Reference K where Davies-Bouldin index reaches its minimum.",
            },
            {
                "item": "duration_hours",
                "description": "The last N hours before the final timestamp of each event record.",
            },
        ]
    )

    with pd.ExcelWriter(summary_path, engine="openpyxl") as writer:
        if not per_event_summary.empty:
            per_event_summary.to_excel(
                writer,
                sheet_name="best_k_by_event_duration",
                index=False,
            )
        if not global_summary.empty:
            global_summary.to_excel(
                writer,
                sheet_name="global_best_k_by_duration",
                index=False,
            )
        all_metrics.to_excel(writer, sheet_name="all_k_metrics", index=False)
        readme.to_excel(writer, sheet_name="README", index=False)

    per_event_summary.to_csv(
        TABLE_DIR / "best_k_by_event_duration.csv",
        index=False,
        encoding="utf-8-sig",
    )
    global_summary.to_csv(
        TABLE_DIR / "global_best_k_by_duration.csv",
        index=False,
        encoding="utf-8-sig",
    )
    all_metrics.to_csv(
        TABLE_DIR / "all_k_metrics.csv",
        index=False,
        encoding="utf-8-sig",
    )

    return summary_path


def save_dec_k_lookup(per_event_summary: pd.DataFrame, global_summary: pd.DataFrame) -> None:
    """
    Save compact lookup tables for future DEC scripts.

    The per-event CSV can be read by event and duration:
        event, duration_hours, recommended_k

    The global CSV can be read by duration:
        duration_hours, recommended_k
    """
    if not per_event_summary.empty:
        per_event_lookup = per_event_summary[
            [
                "event",
                "duration_hours",
                "recommended_k",
                "best_k_wcss_elbow",
                "best_k_silhouette",
                "best_k_calinski_harabasz",
                "best_k_davies_bouldin",
            ]
        ].copy()
        per_event_lookup.to_csv(
            OUTPUT_DIR / "dec_k_lookup_by_event_duration.csv",
            index=False,
            encoding="utf-8-sig",
        )

    if not global_summary.empty:
        global_lookup = global_summary[
            [
                "duration_hours",
                "recommended_k",
                "best_k_wcss_elbow",
                "best_k_silhouette",
                "best_k_calinski_harabasz",
                "best_k_davies_bouldin",
            ]
        ].copy()
        global_lookup.to_csv(
            OUTPUT_DIR / "dec_k_lookup_global_duration.csv",
            index=False,
            encoding="utf-8-sig",
        )


