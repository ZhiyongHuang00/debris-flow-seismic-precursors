# 3. Main workflow
# =========================================================
def run_per_event_analysis() -> tuple[pd.DataFrame, pd.DataFrame]:
    """Calculate K values for each event and each duration."""
    files = sorted(PER_EVENT_NPZ_DIR.glob(PER_EVENT_NPZ_PATTERN), key=lambda p: natural_event_id(p.name))
    if not files:
        raise FileNotFoundError(f"No npz files found in {PER_EVENT_NPZ_DIR}")

    all_metric_frames: list[pd.DataFrame] = []
    summary_rows: list[dict[str, object]] = []

    for npz_path in files:
        event_name = event_from_filename(npz_path)
        print(f"\n[Per-event] Loading {event_name}: {npz_path.name}")
        block = load_feature_block(npz_path, fallback_event=event_name)

        for duration_hours in DURATION_HOURS:
            print(f"  duration={duration_hours:g} h")
            try:
                metric_df, summary = analyse_one_block(
                    block=block,
                    duration_hours=duration_hours,
                    analysis_scope=event_name,
                    use_minibatch=False,
                )
            except Exception as exc:
                warnings.warn(f"Failed {event_name}, duration={duration_hours}: {exc}")
                continue

            summary["event"] = event_name
            summary["event_id"] = natural_event_id(event_name)
            all_metric_frames.append(metric_df.assign(event=event_name, event_id=natural_event_id(event_name)))
            summary_rows.append(summary)

            figure_path = FIGURE_DIR / "per_event" / f"{event_name}_last_{duration_hours:g}h_k_metrics.png"
            plot_metric_curves(metric_df, summary, figure_path)

    summary_df = pd.DataFrame(summary_rows)
    if not summary_df.empty:
        summary_df = summary_df.sort_values(["event_id", "duration_hours"])

    metrics_df = pd.concat(all_metric_frames, ignore_index=True) if all_metric_frames else pd.DataFrame()
    return summary_df, metrics_df


def run_global_analysis() -> tuple[pd.DataFrame, pd.DataFrame]:
    """Calculate global K values by merging all events at each duration."""
    if not GLOBAL_NPZ.exists():
        warnings.warn(f"Global npz not found, skip global analysis: {GLOBAL_NPZ}")
        return pd.DataFrame(), pd.DataFrame()

    print(f"\n[Global] Loading {GLOBAL_NPZ}")
    block = load_feature_block(GLOBAL_NPZ)

    all_metric_frames: list[pd.DataFrame] = []
    summary_rows: list[dict[str, object]] = []

    for duration_hours in DURATION_HOURS:
        print(f"\n[Global] duration={duration_hours:g} h")
        try:
            metric_df, summary = analyse_one_block(
                block=block,
                duration_hours=duration_hours,
                analysis_scope="global_all_events",
                use_minibatch=USE_MINIBATCH_FOR_GLOBAL,
            )
        except Exception as exc:
            warnings.warn(f"Failed global duration={duration_hours}: {exc}")
            continue

        all_metric_frames.append(metric_df)
        summary_rows.append(summary)

        figure_path = FIGURE_DIR / "global" / f"global_last_{duration_hours:g}h_k_metrics.png"
        plot_metric_curves(metric_df, summary, figure_path)

    summary_df = pd.DataFrame(summary_rows)
    if not summary_df.empty:
        summary_df = summary_df.sort_values("duration_hours")

    metrics_df = pd.concat(all_metric_frames, ignore_index=True) if all_metric_frames else pd.DataFrame()
    return summary_df, metrics_df


def main() -> None:
    OUTPUT_DIR.mkdir(parents=True, exist_ok=True)
    FIGURE_DIR.mkdir(parents=True, exist_ok=True)
    TABLE_DIR.mkdir(parents=True, exist_ok=True)

    per_event_summary = pd.DataFrame()
    per_event_metrics = pd.DataFrame()
    global_summary = pd.DataFrame()
    global_metrics = pd.DataFrame()

    if RUN_PER_EVENT_ANALYSIS:
        per_event_summary, per_event_metrics = run_per_event_analysis()

    if RUN_GLOBAL_ANALYSIS:
        global_summary, global_metrics = run_global_analysis()

    all_metrics = pd.concat(
        [per_event_metrics, global_metrics],
        ignore_index=True,
    )

    summary_path = write_excel_outputs(
        per_event_summary=per_event_summary,
        global_summary=global_summary,
        all_metrics=all_metrics,
    )
    save_dec_k_lookup(per_event_summary, global_summary)

    print("\nDone.")
    print(f"Summary workbook: {summary_path}")
    print(f"Compact DEC lookup tables: {OUTPUT_DIR}")
    print(f"Figures: {FIGURE_DIR}")


if __name__ == "__main__":
    main()
