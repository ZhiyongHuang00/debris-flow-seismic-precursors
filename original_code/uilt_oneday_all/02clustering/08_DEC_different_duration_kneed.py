SCRIPT_DIR = Path(__file__).resolve().parent

# Per-event latent features generated by the autoencoder.
PER_EVENT_NPZ_DIR = SCRIPT_DIR / "result" / "all_parameters"
PER_EVENT_NPZ_PATTERN = "*_ACE_model.npz"

# Global latent features generated by the all-event autoencoder.
GLOBAL_NPZ = (
    SCRIPT_DIR
    / "result_all_event"
    / "all_parameters"
    / "all_events_ACE_model_light.npz"
)

