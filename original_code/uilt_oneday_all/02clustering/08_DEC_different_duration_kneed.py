FIGURE_DIR = OUTPUT_DIR / "figures"
TABLE_DIR = OUTPUT_DIR / "tables"

# Duration windows before the end of each event record.
# The current one-day data have one 60 s sample per row, so 1 h contains about
# 60 samples. You can change this list directly for extra analyses.
DURATION_HOURS = [1, 2, 3, 4, 6, 8, 12, 18, 24]

# K range for the supplementary DEC analysis.
K_MIN = 2
K_MAX = 8

RANDOM_STATE = 42
N_INIT = 20
STANDARDIZE_FEATURES = True

# Large merged datasets are faster with MiniBatchKMeans; per-event datasets use
# standard KMeans.
RUN_PER_EVENT_ANALYSIS = True
RUN_GLOBAL_ANALYSIS = True
USE_MINIBATCH_FOR_GLOBAL = True
GLOBAL_BATCH_SIZE = 4096

# Silhouette can be slow for the merged all-event windows.
MAX_SILHOUETTE_SAMPLES = 20000

# If the elbow cannot be estimated, use this fallback.
DEFAULT_K = 3


