def load_base_module():
    """Load the original KMeans evidence script as a reusable module."""
    if not BASE_SCRIPT.exists():
        raise FileNotFoundError(f"Base evidence script not found: {BASE_SCRIPT}")

    spec = importlib.util.spec_from_file_location("kmeans_physical_evidence_base", BASE_SCRIPT)
    if spec is None or spec.loader is None:
        raise ImportError(f"Cannot import base evidence script: {BASE_SCRIPT}")

    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


def safe_compute_feature_tests(base, result_df: pd.DataFrame, features: list[str]) -> tuple[pd.DataFrame, pd.DataFrame]:
    """
    A slightly safer version of the base feature-test function.

    SciPy raises an exception when all values are identical across all groups.
    For that case the feature is not separable, so we record p=1 and effect=0.
    """
    test_rows = []
    pair_rows = []
    clusters = sorted(result_df[base.GROUP_COLUMN].dropna().unique())

    for feature in features:
        groups = [
            pd.to_numeric(result_df.loc[result_df[base.GROUP_COLUMN] == cluster, feature], errors="coerce")
            .dropna()
            .to_numpy(dtype=float)
            for cluster in clusters
        ]
        valid_groups = [group for group in groups if len(group) > 0]

        if len(valid_groups) >= 2:
            try:
                h_stat, p_value = kruskal(*valid_groups)
                epsilon2 = base.kruskal_epsilon_squared(valid_groups, h_stat)
            except ValueError:
                h_stat, p_value, epsilon2 = 0.0, 1.0, 0.0
        else:
            h_stat, p_value, epsilon2 = np.nan, np.nan, np.nan

        test_rows.append({
            "feature": feature,
            "feature_group": base.feature_group(feature),
            "kruskal_h": h_stat,
            "p_value": p_value,
            "epsilon_squared": epsilon2,
            "n_clusters": len(valid_groups),
        })

        for i, cluster_i in enumerate(clusters):
            for cluster_j in clusters[i + 1:]:
                values_i = pd.to_numeric(
                    result_df.loc[result_df[base.GROUP_COLUMN] == cluster_i, feature],
                    errors="coerce",
                ).dropna()
                values_j = pd.to_numeric(
                    result_df.loc[result_df[base.GROUP_COLUMN] == cluster_j, feature],
                    errors="coerce",
                ).dropna()

                if len(values_i) and len(values_j):
                    try:
                        stat, pair_p = mannwhitneyu(values_i, values_j, alternative="two-sided")
                    except ValueError:
                        stat, pair_p = np.nan, 1.0
                else:
                    stat, pair_p = np.nan, np.nan

                pair_rows.append({
                    "feature": feature,
                    "feature_group": base.feature_group(feature),
                    "cluster_i": cluster_i,
                    "cluster_j": cluster_j,
                    "median_i": values_i.median(),
                    "median_j": values_j.median(),
                    "median_difference_i_minus_j": values_i.median() - values_j.median(),
                    "mannwhitney_u": stat,
                    "p_value": pair_p,
                })

    test_df = pd.DataFrame(test_rows)
    pair_df = pd.DataFrame(pair_rows)

    if not test_df.empty:
        test_df = test_df.sort_values(["p_value", "epsilon_squared"], ascending=[True, False])
    if not pair_df.empty:
        pair_df = pair_df.sort_values(["feature", "p_value"])

    return test_df, pair_df


def configure_base_module(base):
    """Redirect the reusable base script to the KMeans-2 result folder."""
    if not KMEANS2_RESULT_FILE.exists():
        raise FileNotFoundError(f"KMeans-2 result workbook not found: {KMEANS2_RESULT_FILE}")

    base.KMEANS_DIR = KMEANS2_DIR
    base.KMEANS_RESULT_FILE = KMEANS2_RESULT_FILE
    base.OUT_DIR = OUT_DIR
    base.GROUP_COLUMN = "kmeans_cluster"
    base.EVENT_COLUMN = "event"
    base.PRECURSOR_CLUSTER_COLUMN = "cluster_id"
    base.compute_feature_tests = lambda result_df, features: safe_compute_feature_tests(base, result_df, features)
    return base


def write_excel_sheet(writer: pd.ExcelWriter, df: pd.DataFrame, sheet_name: str) -> None:
    """Write a sheet even when the dataframe is empty."""
    if df is None:
        df = pd.DataFrame()
    df.to_excel(writer, sheet_name=sheet_name[:31], index=False)


def main() -> None:
    base = configure_base_module(load_base_module())
    base.OUT_DIR.mkdir(parents=True, exist_ok=True)

    result_df = base.load_kmeans_results()
    print("Loaded KMeans-2 precursor-mode result:")
    print(result_df.groupby(base.GROUP_COLUMN).size())

    spec_info_df, spec_centers = base.build_spectrogram_centers(result_df)
    if spec_info_df.empty:
        raise RuntimeError("No spectrogram centers were recovered from NPZ files.")

    stft_path = base.plot_kmeans_spectrogram_centers(spec_info_df, spec_centers)
    psd_path, psd_df, psd_summary_df = base.plot_kmeans_psd_profiles(spec_info_df, spec_centers)

    hourly_df = base.build_hourly_count_table(result_df)
    hourly_path = base.plot_hourly_evolution(hourly_df) if not hourly_df.empty else None

    waveform_info_df, waveform_centers = base.build_waveform_centers(result_df)
    if waveform_info_df.empty:
        corr_df = pd.DataFrame()
        pair_similarity_df = pd.DataFrame()
        corr_path = None
        sim_box_path = None
        sim_summary_df = pd.DataFrame()
    else:
        corr_df, pair_similarity_df = base.compute_correlation_matrix(waveform_info_df, waveform_centers)
        corr_path = base.plot_correlation_matrix(waveform_info_df, corr_df)
        sim_box_path, sim_summary_df = base.plot_within_between_similarity(pair_similarity_df)

    selected_features, feature_source = base.load_top_feature_names(result_df)
    feature_test_df, pairwise_feature_test_df = base.compute_feature_tests(result_df, selected_features)
    feature_boxplot_path = base.plot_feature_boxplots(result_df, selected_features)

    mode_interpretation_df = base.build_mode_interpretation_table(
        result_df=result_df,
        psd_summary_df=psd_summary_df,
        hourly_df=hourly_df,
        feature_test_df=feature_test_df,
        selected_features=selected_features,
    )

    workbook_path = base.OUT_DIR / WORKBOOK_NAME
    with pd.ExcelWriter(workbook_path, engine="openpyxl") as writer:
        write_excel_sheet(writer, result_df, "kmeans2_mode_objects")
        write_excel_sheet(writer, mode_interpretation_df, "mode_interpretation")
        write_excel_sheet(writer, spec_info_df, "spectrogram_centers")
        write_excel_sheet(writer, psd_df, "frequency_profiles")
        write_excel_sheet(writer, psd_summary_df, "frequency_summary")
        write_excel_sheet(writer, hourly_df, "hourly_counts")
        write_excel_sheet(writer, waveform_info_df, "waveform_centers")

        if not corr_df.empty:
            corr_df.reset_index(names="center_key").to_excel(
                writer,
                sheet_name="waveform_corr_matrix",
                index=False,
            )
        else:
            write_excel_sheet(writer, corr_df, "waveform_corr_matrix")

        write_excel_sheet(writer, pair_similarity_df, "waveform_pair_similarity")
        write_excel_sheet(writer, sim_summary_df, "similarity_summary")
        write_excel_sheet(
            writer,
            pd.DataFrame({"selected_feature": selected_features, "source": feature_source}),
            "selected_features",
        )
        write_excel_sheet(writer, feature_test_df, "feature_kruskal_tests")
        write_excel_sheet(writer, pairwise_feature_test_df, "feature_pairwise_tests")

    print("\nSaved KMeans-2 physical-process figures:")
    for path in [stft_path, psd_path, hourly_path, corr_path, sim_box_path, feature_boxplot_path]:
        if path is not None:
            print(path)

    print(f"\nSelected feature source: {feature_source}")
    print(f"Saved workbook: {workbook_path}")


if __name__ == "__main__":
    main()
