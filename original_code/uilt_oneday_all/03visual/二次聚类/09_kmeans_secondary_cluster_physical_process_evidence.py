def compute_event_spectrogram_center(event: str, precursor_cluster: int) -> np.ndarray | None:
    npz_file = find_npz_file(event)
    if npz_file is None:
        return None

    npz = np.load(npz_file, allow_pickle=True)
    if "spectral" not in npz.files or "y_pred_last" not in npz.files:
        return None

    labels = np.asarray(npz["y_pred_last"]).astype(int)
    indices = np.where(labels == precursor_cluster)[0]
    indices = select_evenly_spaced(indices, MAX_SPECTROGRAMS_PER_CENTER)
    if indices.size == 0:
        return None

    spectral = np.asarray(npz["spectral"][indices], dtype=float)
    spectral = np.squeeze(spectral)
    if spectral.ndim == 2:
        spectral = spectral[None, :, :]
    if spectral.ndim != 3:
        return None

    normalized = np.stack([robust_normalize_image(item) for item in spectral], axis=0)
    if CENTER_METHOD == "mean":
        return np.nanmean(normalized, axis=0)
    return np.nanmedian(normalized, axis=0)


def build_spectrogram_centers(result_df: pd.DataFrame) -> tuple[pd.DataFrame, dict[str, np.ndarray]]:
    rows = []
    centers: dict[str, np.ndarray] = {}

    for row in result_df.itertuples(index=False):
        event = str(getattr(row, EVENT_COLUMN))
        precursor_cluster = int(getattr(row, PRECURSOR_CLUSTER_COLUMN))
        mode = int(getattr(row, GROUP_COLUMN))
        key = f"{event}_C{precursor_cluster}"

        print(f"Computing spectrogram center: kmeans_mode={mode}, {key}")
        center = compute_event_spectrogram_center(event, precursor_cluster)
        if center is None:
            continue

        centers[key] = center
        rows.append({
            "kmeans_cluster": mode,
            "event": event,
            "precursor_cluster": precursor_cluster,
            "center_key": key,
            "frequency_bins": int(center.shape[0]),
            "time_bins": int(center.shape[1]),
        })

    return pd.DataFrame(rows), centers


