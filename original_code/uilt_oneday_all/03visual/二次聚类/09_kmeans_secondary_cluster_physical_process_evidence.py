def read_center_waveform(event: str, precursor_cluster: int) -> tuple[np.ndarray, np.ndarray] | None:
    npz_file = find_npz_file(event)
    if npz_file is None:
        return None

    npz = np.load(npz_file, allow_pickle=True)
    if "y_pred_last" not in npz.files or "x_file" not in npz.files:
        return None

    labels = np.asarray(npz["y_pred_last"]).astype(int)
    x_files = np.asarray(npz["x_file"])
    indices = np.where(labels == precursor_cluster)[0]
    indices = select_evenly_spaced(indices, MAX_WAVEFORMS_PER_CENTER)

    waveforms = []
    time_ref = None
    for idx in indices:
        sac_path = resolve_sac_path(x_files[idx])
        if sac_path is None:
            continue
        try:
            tr = read(str(sac_path))[0]
        except Exception:
            continue

        sampling_rate = float(tr.stats.sampling_rate)
        data = tr.data.astype(float)
        if MAX_SECONDS is not None:
            data = data[: int(MAX_SECONDS * sampling_rate)]
        if NORMALIZE_EACH_WAVEFORM:
            data = robust_normalize_vector(data)

        if time_ref is None:
            time_ref = np.arange(len(data)) / sampling_rate
        waveforms.append(data)

    if not waveforms or time_ref is None:
        return None

    min_len = min(len(item) for item in waveforms)
    stack = np.vstack([item[:min_len] for item in waveforms])
    center = np.nanmean(stack, axis=0) if CENTER_METHOD == "mean" else np.nanmedian(stack, axis=0)
    center = robust_normalize_vector(center)
    return time_ref[:min_len], center


def build_waveform_centers(result_df: pd.DataFrame) -> tuple[pd.DataFrame, dict[str, np.ndarray]]:
    rows = []
    centers = {}

    for row in result_df.itertuples(index=False):
        event = str(getattr(row, EVENT_COLUMN))
        precursor_cluster = int(getattr(row, PRECURSOR_CLUSTER_COLUMN))
        mode = int(getattr(row, GROUP_COLUMN))
        key = f"{event}_C{precursor_cluster}"

        print(f"Computing waveform center: kmeans_mode={mode}, {key}")
        result = read_center_waveform(event, precursor_cluster)
        if result is None:
            continue
        _, center = result
        centers[key] = center
        rows.append({
            "kmeans_cluster": mode,
            "event": event,
            "precursor_cluster": precursor_cluster,
            "center_key": key,
        })

    info_df = pd.DataFrame(rows)
    info_df["event_order"] = info_df["event"].map(natural_event_key)
    info_df = info_df.sort_values([GROUP_COLUMN, "event_order"]).drop(columns=["event_order"]).reset_index(drop=True)
    return info_df, centers


def compute_correlation_matrix(center_info: pd.DataFrame, centers: dict[str, np.ndarray]) -> tuple[pd.DataFrame, pd.DataFrame]:
    keys = center_info["center_key"].tolist()
    if len(keys) < 2:
        return pd.DataFrame(), pd.DataFrame()

    min_len = min(len(centers[key]) for key in keys)
    matrix = np.vstack([centers[key][:min_len] for key in keys])
    corr = np.corrcoef(matrix)
    corr_df = pd.DataFrame(corr, index=keys, columns=keys)

    pair_rows = []
    for i, key_i in enumerate(keys):
        for j in range(i + 1, len(keys)):
            key_j = keys[j]
            cluster_i = int(center_info.loc[center_info["center_key"] == key_i, GROUP_COLUMN].iloc[0])
            cluster_j = int(center_info.loc[center_info["center_key"] == key_j, GROUP_COLUMN].iloc[0])
            pair_rows.append({
                "center_i": key_i,
                "center_j": key_j,
                "cluster_i": cluster_i,
                "cluster_j": cluster_j,
                "pair_type": "within" if cluster_i == cluster_j else "between",
                "correlation": corr[i, j],
            })

    return corr_df, pd.DataFrame(pair_rows)


