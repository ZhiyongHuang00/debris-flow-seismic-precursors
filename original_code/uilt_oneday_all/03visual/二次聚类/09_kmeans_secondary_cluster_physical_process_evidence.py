def natural_event_key(value: object) -> tuple[int, str]:
    text = str(value)
    match = re.search(r"(\d+)$", text)
    return (int(match.group(1)) if match else 10**9, text)


def save_fig(path: Path) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    plt.tight_layout()
    plt.savefig(path, dpi=300, bbox_inches="tight")
    plt.close()


def find_npz_file(event: str) -> Path | None:
    for name in [f"{event}_all_parement.npz", f"{event}_all_parameter.npz"]:
        candidate = NPZ_DIR / name
        if candidate.exists():
            return candidate
    files = sorted(NPZ_DIR.glob(f"{event}*.npz"))
    return files[0] if files else None


def parse_timestamp_from_x_file(x_file: object) -> pd.Timestamp | None:
    name = str(x_file).replace("\\", "/").split("/")[-1]
    match = re.search(r"(20\d{6}T\d{6})", name)
    if not match:
        return None
    return pd.to_datetime(match.group(1), format="%Y%m%dT%H%M%S", errors="coerce")


def resolve_sac_path(x_file: object) -> Path | None:
    raw = Path(str(x_file).replace("\\", "/"))
    candidates: list[Path] = []

    if raw.is_absolute():
        candidates.append(raw)
    else:
        candidates.extend([
            SEGMENT_BASE_DIR / raw,
            PROJECT_ROOT / raw,
        ])

    raw_parts = raw.parts
    if "output_segments" in raw_parts:
        idx = raw_parts.index("output_segments")
        tail = Path(*raw_parts[idx + 1 :])
        candidates.append(SEGMENT_BASE_DIR / "output_segments" / tail)

    for candidate in candidates:
        if candidate.exists():
            return candidate

    matches = list((PROJECT_ROOT / "uilt_oneday_all").rglob(raw.name))
    return matches[0] if matches else None


def select_evenly_spaced(indices: np.ndarray, max_count: int | None) -> np.ndarray:
    if max_count is None or indices.size <= max_count:
        return indices
    positions = np.linspace(0, indices.size - 1, max_count).round().astype(int)
    return indices[positions]


def robust_normalize_vector(data: np.ndarray) -> np.ndarray:
    data = np.asarray(data, dtype=float)
    data = data - np.nanmedian(data)
    scale = np.nanmax(np.abs(data))
    if np.isfinite(scale) and scale > 0:
        data = data / scale
    return data


def robust_normalize_image(image: np.ndarray) -> np.ndarray:
    image = np.asarray(image, dtype=float)
    image = np.squeeze(image)
    fill = np.nanmedian(image)
    image = np.nan_to_num(image, nan=fill, posinf=np.nanmax(image), neginf=np.nanmin(image))

    if NORMALIZE_EACH_SPECTROGRAM:
        p1, p99 = np.nanpercentile(image, [1, 99])
        if np.isfinite(p1) and np.isfinite(p99) and p99 > p1:
            image = np.clip(image, p1, p99)
            image = (image - p1) / (p99 - p1)
        else:
            image = image - np.nanmin(image)
            scale = np.nanmax(image)
            if np.isfinite(scale) and scale > 0:
                image = image / scale
    return image


def spectrogram_extent(image: np.ndarray) -> list[float]:
    """Map resized spectrogram-array coordinates back to the 1-min window."""
    return [0.0, MAX_SECONDS, 0.0, NYQUIST_HZ]


def frequency_axis_hz(n_bins: int) -> np.ndarray:
    """Frequency coordinate for PSD-like profiles derived from spectrogram rows."""
    return np.linspace(0.0, NYQUIST_HZ, int(n_bins), dtype=float)


def feature_group(name: str) -> str:
    key = name.lower()
    if any(token in key for token in ["rectilinearity", "azimuth", "dip", "planarity", "polar"]):
        return "polarization"
    if any(token in key for token in ["fft", "freq", "fmax", "fcentroid", "fquart", "spect", "gamma"]):
        return "frequency"
    if any(token in key for token in ["energy", "rms", "peak_amplitude", "amp", "density"]):
        return "energy"
    if any(token in key for token in ["kurto", "skew", "iqr", "env", "duration", "corpeak", "asdec"]):
        return "time"
    if any(token in key for token in ["nbrpeak", "ratioenv", "distq", "distmax", "int_ratio"]):
        return "time_frequency"
    return "other"


def load_kmeans_results() -> pd.DataFrame:
    if not KMEANS_RESULT_FILE.exists():
        raise FileNotFoundError(f"KMeans result file not found: {KMEANS_RESULT_FILE}")

    df = pd.read_excel(KMEANS_RESULT_FILE, sheet_name="kmeans_results")
    required = {EVENT_COLUMN, PRECURSOR_CLUSTER_COLUMN, GROUP_COLUMN}
    missing = required - set(df.columns)
    if missing:
        raise KeyError(f"Missing required columns in KMeans result file: {sorted(missing)}")

    df[EVENT_COLUMN] = df[EVENT_COLUMN].astype(str)
    df[PRECURSOR_CLUSTER_COLUMN] = pd.to_numeric(df[PRECURSOR_CLUSTER_COLUMN], errors="coerce").astype(int)
