    plt.xlabel("Pair type")
    plt.ylabel("Pearson correlation")
    plt.grid(axis="y", alpha=0.25)
    out_path = OUT_DIR / "kmeans_within_between_center_waveform_similarity.png"
    save_fig(out_path)

    within = pair_df.loc[pair_df["pair_type"] == "within", "correlation"].dropna()
    between = pair_df.loc[pair_df["pair_type"] == "between", "correlation"].dropna()
    if len(within) and len(between):
        stat, p_value = mannwhitneyu(within, between, alternative="greater")
    else:
        stat, p_value = np.nan, np.nan

    summary = pd.DataFrame([{
        "comparison": "within > between",
        "within_median": within.median(),
        "between_median": between.median(),
        "within_mean": within.mean(),
        "between_mean": between.mean(),
        "mannwhitney_u": stat,
        "p_value": p_value,
    }])
    return out_path, summary


