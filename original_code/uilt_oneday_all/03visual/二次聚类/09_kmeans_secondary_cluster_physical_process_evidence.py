def compute_hourly_counts_for_event(event: str, precursor_cluster: int) -> np.ndarray | None:
    npz_file = find_npz_file(event)
    if npz_file is None:
        return None

    npz = np.load(npz_file, allow_pickle=True)
    if "y_pred_last" not in npz.files or "x_file" not in npz.files:
        return None

    labels = np.asarray(npz["y_pred_last"]).astype(int)
    x_files = np.asarray(npz["x_file"])
    timestamps = pd.Series([parse_timestamp_from_x_file(item) for item in x_files])
    valid = timestamps.notna()
    if valid.sum() == 0:
        return None

    timestamps = timestamps[valid].reset_index(drop=True)
    labels = labels[valid.values]
    window_end = timestamps.max() + pd.Timedelta(minutes=1)
    selected_times = timestamps[labels == precursor_cluster]
    counts = np.zeros(N_HOURS, dtype=int)

    for timestamp in selected_times:
        hours_before_end = (window_end - timestamp).total_seconds() / 3600.0
        bin_index = int(np.floor(N_HOURS - hours_before_end))
        if 0 <= bin_index < N_HOURS:
            counts[bin_index] += 1

    return counts


def build_hourly_count_table(result_df: pd.DataFrame) -> pd.DataFrame:
    rows = []
    for row in result_df.itertuples(index=False):
        event = str(getattr(row, EVENT_COLUMN))
        precursor_cluster = int(getattr(row, PRECURSOR_CLUSTER_COLUMN))
        mode = int(getattr(row, GROUP_COLUMN))
        counts = compute_hourly_counts_for_event(event, precursor_cluster)
        if counts is None:
            continue

        record = {
            "kmeans_cluster": mode,
            "event": event,
            "precursor_cluster": precursor_cluster,
            "total_count_24h": int(np.sum(counts)),
            "last_1h_count": int(np.sum(counts[-1:])),
            "last_3h_count": int(np.sum(counts[-3:])),
            "last_6h_count": int(np.sum(counts[-6:])),
            "terminal_to_previous_ratio": float(np.mean(counts[-1:]) / (np.mean(counts[-6:-1]) + 1e-12)),
        }
        for i, count in enumerate(counts):
            record[f"hour_{i - N_HOURS}_to_{i - N_HOURS + 1}"] = int(count)
        rows.append(record)

    return pd.DataFrame(rows)


