def load_top_feature_names(result_df: pd.DataFrame) -> tuple[list[str], str]:
    numeric_features = numeric_feature_columns(result_df)

    try:
        shap_df = pd.read_excel(KMEANS_RESULT_FILE, sheet_name="shap_global_importance")
        ranked = [
            feature
            for feature in shap_df["feature"].dropna().astype(str).tolist()
            if feature in numeric_features
        ]
        if ranked:
            return ranked[:TOP_N_FEATURES], "shap_global_importance"
    except Exception:
        pass

    try:
        rf_df = pd.read_excel(KMEANS_RESULT_FILE, sheet_name="rf_feature_importance")
        ranked = [
            feature
            for feature in rf_df["feature"].dropna().astype(str).tolist()
            if feature in numeric_features
        ]
        if ranked:
            return ranked[:TOP_N_FEATURES], "rf_feature_importance"
    except Exception:
        pass

    grouped = result_df.groupby(GROUP_COLUMN)[numeric_features].mean()
    ranked = grouped.var(axis=0).sort_values(ascending=False).head(TOP_N_FEATURES).index.tolist()
    return ranked, "cluster_mean_variance"


def kruskal_epsilon_squared(groups: list[np.ndarray], h_stat: float) -> float:
    n_total = sum(len(group) for group in groups)
    k = len(groups)
    if n_total <= k:
        return np.nan
    return max(0.0, (h_stat - k + 1) / (n_total - k))


def compute_feature_tests(result_df: pd.DataFrame, features: list[str]) -> tuple[pd.DataFrame, pd.DataFrame]:
    test_rows = []
    pair_rows = []
    clusters = sorted(result_df[GROUP_COLUMN].unique())

    for feature in features:
        groups = [
            pd.to_numeric(result_df.loc[result_df[GROUP_COLUMN] == cluster, feature], errors="coerce")
            .dropna()
            .to_numpy(dtype=float)
            for cluster in clusters
        ]
        valid_groups = [group for group in groups if len(group) > 0]

        if len(valid_groups) >= 2:
            h_stat, p_value = kruskal(*valid_groups)
            epsilon2 = kruskal_epsilon_squared(valid_groups, h_stat)
        else:
            h_stat, p_value, epsilon2 = np.nan, np.nan, np.nan

        test_rows.append({
            "feature": feature,
            "feature_group": feature_group(feature),
            "kruskal_h": h_stat,
            "p_value": p_value,
            "epsilon_squared": epsilon2,
            "n_clusters": len(valid_groups),
        })

        for i, cluster_i in enumerate(clusters):
            for cluster_j in clusters[i + 1 :]:
                values_i = pd.to_numeric(result_df.loc[result_df[GROUP_COLUMN] == cluster_i, feature], errors="coerce").dropna()
                values_j = pd.to_numeric(result_df.loc[result_df[GROUP_COLUMN] == cluster_j, feature], errors="coerce").dropna()
                if len(values_i) and len(values_j):
                    try:
                        stat, pair_p = mannwhitneyu(values_i, values_j, alternative="two-sided")
                    except Exception:
                        stat, pair_p = np.nan, np.nan
                else:
                    stat, pair_p = np.nan, np.nan

                pair_rows.append({
                    "feature": feature,
                    "feature_group": feature_group(feature),
                    "cluster_i": cluster_i,
                    "cluster_j": cluster_j,
                    "median_i": values_i.median(),
                    "median_j": values_j.median(),
                    "median_difference_i_minus_j": values_i.median() - values_j.median(),
                    "mannwhitney_u": stat,
                    "p_value": pair_p,
                })

    test_df = pd.DataFrame(test_rows).sort_values(["p_value", "epsilon_squared"], ascending=[True, False])
    pair_df = pd.DataFrame(pair_rows).sort_values(["feature", "p_value"])
    return test_df, pair_df


def plot_feature_boxplots(result_df: pd.DataFrame, features: list[str]) -> Path:
    n_cols = 4
    n_rows = math.ceil(len(features) / n_cols)
    fig, axes = plt.subplots(n_rows, n_cols, figsize=(4.2 * n_cols, 3.2 * n_rows), squeeze=False)

    for idx, feature in enumerate(features):
        ax = axes[idx // n_cols, idx % n_cols]
        plot_df = result_df[[GROUP_COLUMN, feature]].replace([np.inf, -np.inf], np.nan).dropna()

        if sns is not None:
            sns.boxplot(data=plot_df, x=GROUP_COLUMN, y=feature, showfliers=SHOW_OUTLIERS, color="#9ecae1", ax=ax)
            sns.stripplot(data=plot_df, x=GROUP_COLUMN, y=feature, color="black", alpha=0.55, size=3, jitter=0.18, ax=ax)
        else:
            clusters = sorted(plot_df[GROUP_COLUMN].unique())
            data = [plot_df.loc[plot_df[GROUP_COLUMN] == cluster, feature].values for cluster in clusters]
            ax.boxplot(data, labels=clusters, showfliers=SHOW_OUTLIERS)

        ax.set_title(feature, fontsize=10)
        ax.set_xlabel("KMeans mode")
        ax.set_ylabel("")
        ax.grid(axis="y", alpha=0.25)

    for idx in range(len(features), n_rows * n_cols):
        axes[idx // n_cols, idx % n_cols].axis("off")

    fig.suptitle("Feature separability of precursor centers across KMeans modes", fontsize=15)
    out_path = OUT_DIR / "kmeans_feature_boxplots_and_points_top_features.png"
    save_fig(out_path)
    return out_path


def build_mode_interpretation_table(
    result_df: pd.DataFrame,
    psd_summary_df: pd.DataFrame,
    hourly_df: pd.DataFrame,
    feature_test_df: pd.DataFrame,
    selected_features: list[str],
) -> pd.DataFrame:
    rows = []
    top_features = selected_features[:8]

    for mode in sorted(result_df[GROUP_COLUMN].unique()):
        local = result_df[result_df[GROUP_COLUMN] == mode]
        local_psd = psd_summary_df[psd_summary_df[GROUP_COLUMN] == mode]
        local_hourly = hourly_df[hourly_df[GROUP_COLUMN] == mode]

        feature_direction = []
        for feature in top_features:
            global_median = pd.to_numeric(result_df[feature], errors="coerce").median()
            mode_median = pd.to_numeric(local[feature], errors="coerce").median()
            direction = "high" if mode_median > global_median else "low"
            feature_direction.append(f"{feature}={direction}")

        rows.append({
            "kmeans_cluster": int(mode),
            "n_events": int(len(local)),
            "events": ", ".join(local[EVENT_COLUMN].astype(str).tolist()),
            "median_peak_frequency_bin": local_psd["peak_frequency_bin"].median() if not local_psd.empty else np.nan,
            "median_peak_frequency_hz": local_psd["peak_frequency_hz"].median() if not local_psd.empty else np.nan,
            "median_spectral_centroid_bin": local_psd["spectral_centroid_bin"].median() if not local_psd.empty else np.nan,
            "median_spectral_centroid_hz": local_psd["spectral_centroid_hz"].median() if not local_psd.empty else np.nan,
            "median_high_low_frequency_ratio": local_psd["high_low_frequency_ratio"].median() if not local_psd.empty else np.nan,
            "median_last_1h_count": local_hourly["last_1h_count"].median() if not local_hourly.empty else np.nan,
            "median_last_3h_count": local_hourly["last_3h_count"].median() if not local_hourly.empty else np.nan,
            "median_terminal_to_previous_ratio": local_hourly["terminal_to_previous_ratio"].median() if not local_hourly.empty else np.nan,
            "dominant_feature_directions": "; ".join(feature_direction),
        })

    top_test = feature_test_df.head(10).copy()
    if not top_test.empty:
        rows.append({
            "kmeans_cluster": "overall",
            "n_events": len(result_df),
            "events": "top separable features",
            "dominant_feature_directions": "; ".join(
                [
                    f"{row.feature}(p={row.p_value:.3g}, eps2={row.epsilon_squared:.2f})"
                    for row in top_test.itertuples(index=False)
                ]
            ),
        })

    return pd.DataFrame(rows)


