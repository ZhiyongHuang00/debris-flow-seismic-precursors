def plot_kmeans_psd_profiles(center_info: pd.DataFrame, centers: dict[str, np.ndarray]) -> tuple[Path, pd.DataFrame, pd.DataFrame]:
    rows = []
    summary_rows = []
    plt.figure(figsize=(8, 5))
    cmap = plt.get_cmap("tab10")

    for color_id, group in enumerate(sorted(center_info[GROUP_COLUMN].unique())):
        keys = center_info.loc[center_info[GROUP_COLUMN] == group, "center_key"].tolist()
        profiles = []

        for key in keys:
            spec = centers[key]
            profile = np.nanmean(spec, axis=1)
            profile = profile - np.nanmin(profile)
            scale = np.nanmax(profile)
            if np.isfinite(scale) and scale > 0:
                profile = profile / scale
            profiles.append(profile)

            freq_hz = frequency_axis_hz(len(profile))
            for freq_bin, (freq_value, value) in enumerate(zip(freq_hz, profile)):
                rows.append({
                    "kmeans_cluster": group,
                    "center_key": key,
                    "frequency_bin": freq_bin,
                    "frequency_hz": float(freq_value),
                    "normalized_psd": float(value),
                })

            freq_bin_axis = np.arange(len(profile), dtype=float)
            freq = frequency_axis_hz(len(profile))
            peak_idx = int(np.nanargmax(profile))
            summary_rows.append({
                "kmeans_cluster": group,
                "center_key": key,
                "peak_frequency_bin": peak_idx,
                "peak_frequency_hz": float(freq[peak_idx]),
                "spectral_centroid_bin": float(
                    np.nansum(freq_bin_axis * profile) / (np.nansum(profile) + 1e-12)
                ),
                "spectral_centroid_hz": float(np.nansum(freq * profile) / (np.nansum(profile) + 1e-12)),
                "high_low_frequency_ratio": float(
                    np.nanmean(profile[len(profile) // 2 :]) / (np.nanmean(profile[: len(profile) // 2]) + 1e-12)
                ),
            })

        profiles = np.vstack(profiles)
        freq = frequency_axis_hz(profiles.shape[1])
        median = np.nanmedian(profiles, axis=0)
        q25 = np.nanpercentile(profiles, 25, axis=0)
        q75 = np.nanpercentile(profiles, 75, axis=0)
        color = cmap(color_id % 10)

        plt.plot(freq, median, color=color, linewidth=2, label=f"KMeans {group} (N={len(keys)})")
        plt.fill_between(freq, q25, q75, color=color, alpha=0.18)

    plt.xlabel("Frequency (Hz)")
    plt.ylabel("Normalized PSD-like intensity")
    plt.title("Frequency-energy profiles of KMeans precursor modes")
    plt.grid(alpha=0.25)
    plt.legend()

    out_path = OUT_DIR / "kmeans_mode_psd_profiles.png"
    save_fig(out_path)
    return out_path, pd.DataFrame(rows), pd.DataFrame(summary_rows)


